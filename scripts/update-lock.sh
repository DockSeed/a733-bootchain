# Regenerate container/packages.lock: the complete package set of the builder
# image (base image packages plus everything container/packages.txt asks for,
# with all dependencies) at exact versions, for amd64 and arm64 builders,
# resolved against one snapshot.debian.org timestamp.
#
#   scripts/update-lock.sh                  re-resolve at the current snapshot
#                                           (after a change to packages.txt)
#   scripts/update-lock.sh 20261101T000000Z move to a new snapshot
#
# UPDATE_LOCK_ARCHES limits the builder architectures (default "amd64 arm64");
# a lock without an architecture cannot build the builder image on such a host.
#
# Needs podman or docker (BOOTCHAIN_ENGINE picks one) and network access.
# Nothing is installed anywhere: the base image's package database for each
# architecture is copied out of a created (never started) container and APT
# resolves against it in a throwaway native container. The Containerfile
# checks the result: an image whose installed set differs from the lock fails
# to build. Not needed for a normal build.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/../container" && pwd)"
lock="${here}/packages.lock"
die() { printf '::error:: %s\n' "$*" >&2; exit 1; }

engine="${BOOTCHAIN_ENGINE:-}"
if [ -z "${engine}" ]; then
  if command -v podman >/dev/null 2>&1; then engine=podman
  elif command -v docker >/dev/null 2>&1; then engine=docker
  else die "neither podman nor docker found"; fi
fi

base="$(sed -n 's/^FROM[[:space:]]\{1,\}\([^[:space:]]*\).*/\1/p' "${here}/Containerfile" | head -n1)"
case "${base}" in *@sha256:*) ;; *) die "Containerfile: FROM must pin the base image by digest" ;; esac

ts="${1:-}"
if [ -z "${ts}" ] && [ -f "${lock}" ]; then
  ts="$(sed -n 's/^# snapshot \([0-9TZ]*\)$/\1/p' "${lock}")"
fi
[[ "${ts}" =~ ^[0-9]{8}T[0-9]{6}Z$ ]] || die "give a snapshot timestamp like 20261015T060000Z"

wd="$(mktemp -d "${TMPDIR:-/tmp}/bootchain-lock.XXXXXX")"
trap 'rm -rf "${wd}"' EXIT

read -r -a arches <<<"${UPDATE_LOCK_ARCHES:-amd64 arm64}"
native="$(uname -m)"
case "${native}" in x86_64) native=amd64 ;; aarch64) native=arm64 ;; esac

for arch in "${arches[@]}"; do
  # The base image's dpkg database for <arch>. The container is only created,
  # never started, so this works on any host.
  cid="$("${engine}" create -q --platform "linux/${arch}" "${base}" true)"
  "${engine}" cp "${cid}:/var/lib/dpkg/status" "${wd}/status.${arch}"
  img="$("${engine}" inspect --format '{{.Image}}' "${cid}")"
  "${engine}" rm -f "${cid}" >/dev/null
  # Drop a foreign-architecture copy again so later runs of "${base}" on this
  # host cannot pick it up by mistake.
  [ "${arch}" = "${native}" ] || "${engine}" rmi -f "${img}" >/dev/null 2>&1 || true
done

cp "${here}/install-packages.sh" "${here}/packages.txt" "${wd}/"
mkdir -p "${wd}/ctx"
cp "${here}/packages.txt" "${wd}/ctx/"

# The resolution needs root in the container (APT sources, APT's own state). A
# rootless engine maps that root to the invoking user. A rootful engine would
# leave files in ${wd} that the user cannot remove, so the container hands the
# directory back before it exits.
rootless=false
case "${engine}" in
  podman) [ "$(podman info --format '{{.Host.Security.Rootless}}' 2>/dev/null)" = true ] && rootless=true ;;
  docker) docker info --format '{{.SecurityOptions}}' 2>/dev/null | grep -q rootless && rootless=true ;;
esac
owner=()
if [ "${rootless}" = false ] && [ "$(id -u)" != 0 ]; then
  owner=(-e "LOCK_UID=$(id -u)" -e "LOCK_GID=$(id -g)")
fi

"${engine}" run --rm --platform "linux/${native}" --security-opt label=disable \
  "${owner[@]}" -v "${wd}:/lock" "${base}" \
  bash -c 'if [ -n "${LOCK_UID:-}" ]; then trap "chown -R ${LOCK_UID}:${LOCK_GID} /lock" EXIT; fi
           bash /lock/install-packages.sh "$@"' _ \
  resolve /lock/ctx "${ts}" /lock "${arches[@]}" > "${wd}/lock.body"

{
  printf '# Generated by scripts/update-lock.sh; not edited by hand.\n'
  printf '# The builder image installs exactly these packages, and its build fails if\n'
  printf '# the installed set differs. Format: <builder arch> <package>:<arch>=<version>\n'
  printf '# snapshot %s\n' "${ts}"
  printf '# base %s\n' "${base}"
  printf '# arches %s\n' "${arches[*]}"
  cat "${wd}/lock.body"
} > "${lock}.new"
mv "${lock}.new" "${lock}"
printf 'wrote %s: snapshot %s\n' "${lock}" "${ts}"
for arch in "${arches[@]}"; do printf '  %s: %s packages\n' "${arch}" "$(grep -c "^${arch} " "${lock}")"; done
